    def seed_subtasks_for_request(self, user_message: str) -> list[PlannedSubtask]:
        if self.is_repo_architecture_request(user_message):
            return self.canonical_repo_subtasks(user_message)
        lowered = user_message.lower()
        if any(keyword in lowered for keyword in ["backend", "后端", "server", "api", "runtime"]):
            return self.scoped_backend_subtasks(user_message)
        if any(keyword in lowered for keyword in ["frontend", "前端", "ui", "页面", "router", "react"]):
            return self.scoped_frontend_subtasks(user_message)
        if self.is_path_scoped_request(user_message):
            return self.path_scoped_subtasks(user_message)
        return self.generic_fallback_subtasks(user_message)

    def fallback_subtasks_for_request(self, user_message: str) -> list[PlannedSubtask]:
        if self.is_repo_architecture_request(user_message):
            return self.canonical_repo_subtasks(user_message)
        return self.seed_subtasks_for_request(user_message)

