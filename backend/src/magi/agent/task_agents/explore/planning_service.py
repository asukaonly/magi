"""Planning helpers for ExploreTaskAgent."""
from __future__ import annotations

import json
from typing import Any, Optional

from ....utils.diagnostic_logging import full_content_logging_enabled
from ....core.logger import get_logger
from ....tools.registry import tool_registry
from ....tools.tool_hint_resolver import ToolHintResolver
from ...orchestration import PlannedSubtask, SubtaskPlan
from ..common import OrchestrationPlan
from .prompt_service import ExplorePromptService

logger = get_logger(__name__)

STRUCTURED_PLANNING_TIMEOUT_SECONDS = 180.0


class ExplorePlanningService:
    """Owns LLM-first and fallback Explore subtask generation."""

    _EXPLORE_TOOL_HINT_CANDIDATES = ["glob", "grep", "file_read"]

    def __init__(self, *, prompt_service: ExplorePromptService, tool_hint_resolver: ToolHintResolver | None = None) -> None:
        self._prompt_service = prompt_service
        self._tool_hint_resolver = tool_hint_resolver or ToolHintResolver(tool_registry)

    async def generate_subtask_plan(
        self,
        user_message: str,
        history: list[dict[str, Any]],
        orchestration_plan: OrchestrationPlan,
        user_id: str,
        session_id: str,
        run_id: str | None = None,
        run_revision: int = 0,
        workspace_root: str | None = None,
    ) -> SubtaskPlan:
        _ = (user_id, session_id, run_id, run_revision, workspace_root)
        raw_plan = await self._plan_with_task_agent(
            user_message=user_message,
            history=history,
            orchestration_plan=orchestration_plan,
        )
        if raw_plan is None:
            raw_plan = SubtaskPlan(
                summary="Fallback exploration plan generated by ExploreTaskAgent.",
                subtasks=self.fallback_subtasks_for_request(user_message),
            )
        return self.normalize_subtask_plan(user_message=user_message, raw_plan=raw_plan)

    async def _plan_with_task_agent(
        self,
        *,
        user_message: str,
        history: list[dict[str, Any]],
        orchestration_plan: OrchestrationPlan,
    ) -> Optional[SubtaskPlan]:
        recent_history = [
            {
                "role": str(item.get("role", "unknown")),
                "content": str(item.get("content", ""))[:400],
            }
            for item in history[-4:]
            if isinstance(item, dict) and str(item.get("content", "")).strip()
        ]
        seed_subtasks = self.seed_subtasks_for_request(user_message)
        task_hint = self._resolve_task_hint(user_message)
        planning_prompt = {
            "user_request": user_message,
            "recent_history": recent_history,
            "allow_parallel": orchestration_plan.allow_parallel,
            "scope_hints": self.describe_request_scope(user_message),
            "task_hints": task_hint,
            "seed_subtasks": [item.to_dict() for item in seed_subtasks],
            "requirements": [
                "Decompose the exploration request into bounded CodeExplore leaf subtasks only.",
                "Keep each subtask narrow enough for one worker to finish independently.",
                "Prefer parallel subtasks whenever dependencies are weak.",
                "Start from the most concrete likely anchor or owning code path, then split by neighboring responsibilities only when needed.",
                "Use the seed subtasks as a starting point, but adapt them to the user's actual scope.",
                "If the user is asking about only one subsystem, folder, or path, keep the plan inside that scope.",
                "Prefer execution-ready subtasks that end in validated findings from current source files.",
                "Avoid generic research-only subtasks like 'gather context' or 'summarize risks' unless the request explicitly needs them or ambiguity remains unresolved.",
                "You may remove irrelevant seed subtasks, rewrite them, or add at most two necessary subtasks.",
                "Return between 2 and 6 subtasks unless the request is truly tiny.",
                "Do not include final user-facing prose.",
            ],
        }
        system_prompt = (
            "You are ExploreTaskAgent planning bounded CodeExplore subtasks. "
            "Return ONLY valid JSON with this schema: "
            '{"summary":"string","subtasks":[{"description":"string","subagent_type":"CodeExplore","prompt":"string","parallel_group":"string"}]}. '
            "Do not answer the user directly. Produce execution-ready CodeExplore leaf tasks only. "
            "Prefer subtasks organized around concrete entry points, owning modules, and validating evidence from current files. "
            "When task_hints are present, use them to keep the first search pass efficient and bounded."
        )
        try:
            response = await self._prompt_service.call_llm(
                system_prompt=system_prompt,
                messages=[{"role": "user", "content": json.dumps(planning_prompt, ensure_ascii=False)}],
                disable_thinking=False,
                json_mode=True,
                timeout_seconds=STRUCTURED_PLANNING_TIMEOUT_SECONDS,
            )
        except Exception as exc:
            logger.warning("ExploreTaskAgent planning call failed | error=%s", exc)
            return None
        return self.parse_subtask_plan(response)

    def normalize_subtask_plan(self, *, user_message: str, raw_plan: SubtaskPlan) -> SubtaskPlan:
        raw_subtasks = list(raw_plan.subtasks)
        if not raw_subtasks:
            raw_subtasks = self.fallback_subtasks_for_request(user_message)
        normalized: list[PlannedSubtask] = []
        seen_descriptions: set[str] = set()
        for item in raw_subtasks:
            description = str(item.description).strip()
            prompt = str(item.prompt).strip()
            if not description or not prompt:
                continue
            dedupe_key = description.lower()
            if dedupe_key in seen_descriptions:
                continue
            seen_descriptions.add(dedupe_key)
            normalized.append(
                PlannedSubtask(
                    description=description,
                    subagent_type="CodeExplore",
                    prompt=self.build_leaf_prompt(user_message, description, prompt),
                    parallel_group=str(item.parallel_group or "default").strip() or "default",
                )
            )
            if len(normalized) >= 6:
                break
        if len(normalized) < 2:
            normalized = [
                PlannedSubtask(
                    description=item.description,
                    subagent_type="CodeExplore",
                    prompt=self.build_leaf_prompt(user_message, item.description, item.prompt),
                    parallel_group=item.parallel_group,
                )
                for item in self.fallback_subtasks_for_request(user_message)
            ]
        return SubtaskPlan(summary=raw_plan.summary, subtasks=normalized)

    def parse_subtask_plan(self, response: str) -> Optional[SubtaskPlan]:
        raw = str(response or "").strip()
        if not raw:
            logger.warning("ExploreTaskAgent planning returned empty response")
            return None
        try:
            payload = json.loads(raw)
        except json.JSONDecodeError:
            if full_content_logging_enabled():
                logger.warning(
                    "ExploreTaskAgent planning returned invalid JSON | response_preview=%s",
                    raw[:300],
                )
            else:
                logger.warning(
                    "ExploreTaskAgent planning returned invalid JSON | response_chars=%d",
                    len(raw),
                )
            return None
        if not isinstance(payload, dict):
            return None
        subtasks = payload.get("subtasks")
        if not isinstance(subtasks, list) or not subtasks:
            logger.warning("ExploreTaskAgent planning returned empty subtasks")
            return None
        normalized = SubtaskPlan.from_dict(payload)
        return normalized if normalized.subtasks else None

